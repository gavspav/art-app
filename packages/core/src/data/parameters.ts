export const parameters: Parameter[] = parameterDefinitions.map((parameter) => {
  const description = parameterDescriptions[parameter.id as keyof typeof parameterDescriptions];
  return description ? { ...parameter, description } : parameter;
});

export const parametersById: Map<string, Parameter> = new Map(
  parameters.map((param) => [param.id, param])
);

export const getParameter = (id: string): Parameter | undefined => parametersById.get(id);
